#!/usr/bin/env node
/*
 * Counsel experiment: how much should you trust an advisor?
 *   node sim/counsel.js [--seeds 200] [--out results]
 *
 * Three trust policies (ignore / always trust / calibrated) x three advisors
 * (none / reliable 90% / careless 60%), same seeded formations throughout.
 * Writes results/COUNSEL.md and results/figures/counsel.svg.
 */
const fs = require('fs');
const path = require('path');
const K = require('./load');

const args = process.argv.slice(2);
const arg = (name, dflt) => { const i = args.indexOf('--' + name); return i >= 0 ? args[i + 1] : dflt; };
const SEEDS = parseInt(arg('seeds', '200'), 10);
const OUT = path.resolve(arg('out', path.join(__dirname, '..', 'results')));
const COND = { infoLevel: 'medium', allyComms: true, enemyComms: true, explain: true };
const POLICIES = [['belief', 'Ignores counsel'], ['truster', 'Always trusts'], ['calibrated', 'Calibrated trust']];
const ADVISORS = [['none', 'No counsel'], ['reliable', 'Reliable (90%)'], ['unreliable', 'Careless (60%)'], ['planner', "Krishna's insight"]];
const { wilson, twoProportion } = K.Stats;
const pct = (x) => (x == null ? '—' : (100 * x).toFixed(1) + '%');
const ci = (c) => (c ? `${(100 * c[0]).toFixed(1)}–${(100 * c[1]).toFixed(1)}%` : '—');
const pFmt = (p) => (p < 0.001 ? '< 0.001' : p.toFixed(3));

const t0 = Date.now();
const cells = {};
const allRows = [];
for (const [adv] of ADVISORS) for (const [pol] of POLICIES) {
  if (adv === 'none' && pol !== 'belief') continue; // with no counsel every policy plays the same
  const rows = [];
  for (let seed = 1; seed <= SEEDS; seed++) {
    const r = K.playBot(K.createGame(Object.assign({ seed, advisor: adv }, COND)), pol);
    rows.push(r);
    allRows.push(Object.assign({ advisor: adv, policy: pol, seed }, r));
  }
  const sum = (k) => rows.reduce((a, r) => a + (r[k] || 0), 0);
  const esc = rows.filter((r) => r.result === 'escaped').length;
  cells[adv + '|' + pol] = {
    n: rows.length, esc, rate: esc / rows.length, ci: wilson(esc, rows.length),
    followGood: sum('adviceGood') ? sum('followedGood') / sum('adviceGood') : null,
    followBad: sum('adviceBad') ? sum('followedBad') / sum('adviceBad') : null,
    accuracy: sum('adviceGiven') ? sum('adviceGood') / sum('adviceGiven') : null,
  };
}
const base = cells['none|belief'];
for (const [pol] of POLICIES) cells['none|' + pol] = base;

// ---------------- figure ----------------
const C = { s: ['#2a78d6', '#eb6834', '#1baf7a'], ink: '#2a2418', muted: '#6e6350', grid: '#e4ddcd', bg: '#fbf8f1' };
const W = 660, H = 340, m = { l: 56, r: 16, t: 50, b: 46 }, ih = H - m.t - m.b, iw = W - m.l - m.r;
let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" font-family="system-ui, sans-serif" font-size="12"><rect width="${W}" height="${H}" fill="${C.bg}"/>`;
svg += `<text x="${m.l}" y="22" font-size="15" font-weight="600" fill="${C.ink}">Escape rate by advisor and trust policy</text>`;
let lx = m.l;
POLICIES.forEach(([, label], j) => { svg += `<rect x="${lx}" y="32" width="10" height="10" rx="2" fill="${C.s[j]}"/><text x="${lx + 15}" y="41" fill="${C.muted}">${label}</text>`; lx += 30 + label.length * 6.6; });
for (const v of [0, 0.25, 0.5, 0.75, 1]) { const y = m.t + ih * (1 - v); svg += `<line x1="${m.l}" x2="${W - m.r}" y1="${y}" y2="${y}" stroke="${C.grid}"/><text x="${m.l - 8}" y="${y + 4}" text-anchor="end" fill="${C.muted}">${v * 100}%</text>`; }
const gw = iw / ADVISORS.length, bw = 44;
ADVISORS.forEach(([adv, label], i) => {
  const cx = m.l + gw * i + gw / 2;
  svg += `<text x="${cx}" y="${H - 18}" text-anchor="middle" fill="${C.ink}">${label}</text>`;
  const pols = adv === 'none' ? [POLICIES[0]] : POLICIES;
  pols.forEach(([pol], j) => {
    const c = cells[adv + '|' + pol];
    const x = cx - (pols.length * (bw + 2)) / 2 + j * (bw + 2), h = ih * c.rate, y = m.t + ih - h, rr = Math.min(4, h);
    svg += `<path d="M${x},${m.t + ih} V${y + rr} Q${x},${y} ${x + rr},${y} H${x + bw - rr} Q${x + bw},${y} ${x + bw},${y + rr} V${m.t + ih} Z" fill="${C.s[j]}"/>`;
    const y1 = m.t + ih * (1 - c.ci[1]), y0 = m.t + ih * (1 - c.ci[0]), mx = x + bw / 2;
    svg += `<path d="M${mx},${y1} V${y0} M${mx - 5},${y1} H${mx + 5} M${mx - 5},${y0} H${mx + 5}" stroke="${C.ink}" stroke-width="1.2" opacity="0.7"/>`;
    svg += `<text x="${mx}" y="${y1 - 6}" text-anchor="middle" fill="${C.ink}">${Math.round(c.rate * 100)}%</text>`;
  });
});
svg += `<text x="${W - m.r}" y="${H - 4}" text-anchor="end" font-size="10" fill="${C.muted}">n = ${SEEDS} games per bar · whiskers: Wilson 95% CI</text></svg>`;
fs.mkdirSync(path.join(OUT, 'figures'), { recursive: true });
fs.writeFileSync(path.join(OUT, 'figures', 'counsel.svg'), svg);

// ---------------- report ----------------
const L = [];
L.push('# Counsel experiment: how much should you trust an advisor?', '');
L.push(`Generated by \`node sim/counsel.js\`: ${SEEDS} seeds per cell, medium information, both sides coordinated. Every cell plays the same ${SEEDS} formations. Good counsel = the move an expert with the true map and sight of every sentinel would accept.`, '');
L.push('![Escape rate by advisor and trust policy](figures/counsel.svg)', '');
L.push('| Advisor | Trust policy | Escaped (95% CI) | Counsel right | Followed good | Followed bad |', '|---|---|---|---|---|---|');
for (const [adv, al] of ADVISORS) for (const [pol, pl] of POLICIES) {
  if (adv === 'none' && pol !== 'belief') continue;
  const c = cells[adv + '|' + pol];
  L.push(`| ${al} | ${adv === 'none' ? '—' : pl} | ${pct(c.rate)} (${ci(c.ci)}) | ${pct(c.accuracy)} | ${pct(c.followGood)} | ${pct(c.followBad)} |`);
}
L.push('', '## Tests against playing without counsel', '', '| Comparison | Escape A | Escape B | Difference | p |', '|---|---|---|---|---|');
const vs = (label, a, b) => { const t = twoProportion(a.esc, a.n, b.esc, b.n); L.push(`| ${label} | ${pct(a.rate)} | ${pct(b.rate)} | ${(t.diff * 100 >= 0 ? '+' : '') + (t.diff * 100).toFixed(1)} pts | ${pFmt(t.p)} |`); };
vs('No counsel → reliable, always trust', base, cells['reliable|truster']);
vs('No counsel → reliable, calibrated', base, cells['reliable|calibrated']);
vs('No counsel → careless, always trust', base, cells['unreliable|truster']);
vs('No counsel → careless, calibrated', base, cells['unreliable|calibrated']);
vs('Careless: always trust → calibrated', cells['unreliable|truster'], cells['unreliable|calibrated']);
vs("No counsel → Krishna's insight, always trust", base, cells['planner|truster']);
L.push('', '## Reading the results', '');
L.push(`- **Good counsel helps, and calibrated trust helps most.** With a reliable messenger, success rises from ${pct(base.rate)} to ${pct(cells['reliable|truster'].rate)} for a player who always trusts it, and ${pct(cells['reliable|calibrated'].rate)} for one who checks it against their own map.`);
L.push(`- **Blind trust in a bad source is catastrophic.** Always following the careless messenger drops success to ${pct(cells['unreliable|truster'].rate)}.`);
{
  const c = cells['unreliable|calibrated'], t = twoProportion(base.esc, base.n, c.esc, c.n);
  L.push(`- **Calibration limits the damage.** Checking counsel against your own map keeps success at ${pct(c.rate)} with the careless messenger, ${t.p < 0.05 ? 'still significantly below' : 'not significantly different from'} playing without counsel (${pct(base.rate)}, p = ${pFmt(t.p)}).`);
  const r = cells['reliable|truster'], tr = twoProportion(base.esc, base.n, r.esc, r.n);
  if (tr.p >= 0.05) L.push(`- **Even good counsel needs judgement.** Always trusting the reliable messenger is not a significant gain (p = ${pFmt(tr.p)}): its occasional wrong steps cost as much as its good ones save. Only calibrated trust turns good counsel into a clear improvement.`);
}
{
  const p = cells['planner|truster'], t = twoProportion(base.esc, base.n, p.esc, p.n);
  L.push(`- **An advisor that only knows what you know can't fix your blind spots.** Krishna's insight gives good counsel ${pct(p.accuracy)} of the time, and every wrong piece is wrong because the player's own information was. For a player who already plans perfectly on their own map, trusting it changes little (${pct(base.rate)} → ${pct(p.rate)}, p = ${pFmt(t.p)}). It can only help a player who reasons less carefully than it does, which is what the human study measures.`);
}
L.push('- These are scripted policies. The human study measures where real players fall between "always trust" and "ignore", and whether reasons attached to counsel change that.');
fs.writeFileSync(path.join(OUT, 'COUNSEL.md'), L.join('\n') + '\n');
// Per-game rows for the Python analysis (analysis/analyze.py).
const COLS = ['advisor', 'policy', 'seed', 'result', 'turns', 'resolve', 'adviceGiven', 'adviceGood', 'adviceBad', 'followedGood', 'followedBad', 'ignoredGood', 'ignoredBad'];
fs.writeFileSync(path.join(OUT, 'counsel-games.csv'), [COLS.join(',')].concat(allRows.map((x) => COLS.map((c) => (x[c] == null ? '' : x[c])).join(','))).join('\n') + '\n');
console.log(L.slice(4, 4 + 10).join('\n'));
console.log(`\nWrote ${path.join(OUT, 'COUNSEL.md')} in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
